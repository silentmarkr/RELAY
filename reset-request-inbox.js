'use strict';
const crypto = require('crypto');
const { generatePairingCode, normalizePairingCode } = require('./client-activation-security');
const { decodeRequestCode } = require('./bir-passkey');

// RESET REQUEST INBOX (kept in RELAY memory only).
// Same idea as the activation waiting room (client-activation-inbox.js), but for the two BIR resets of an already activated
// client: System Hard Reset (while BIR records exist) and the AGT reset.
//
//   client dialog  --polls with its BIR request code-->  RELAY   (RELAY answers with a PAIRING CODE to read to the developer)
//   developer      --reviews the request, presses "Send pass key"-->  RELAY signs the pass key and puts it in this inbox
//   client dialog  --next poll-->  receives the pass key, which enables its final reset button
//
// Safety properties:
//  - nothing is trusted from the client except what the developer reviews: the request code is parsed with the same strict
//    decoder the manual flow uses, and the request must belong to the installation of the authenticated client credential;
//  - an entry is keyed by the request nonce, so a second device cannot read or block the delivery meant for another one;
//  - the signed pass key lives only in memory, only until it expires, and is never returned by list();
//  - the number of entries is capped so polling cannot grow memory without limit.
const ONLINE_MS = 45 * 1000;              // a client that polled within this window counts as waiting right now
const WAIT_ENTRY_TTL_MS = 2 * 60 * 1000;  // an entry with nothing delivered disappears this long after its last poll
const MAX_ENTRIES = 200;
const NONCE_RE = /^[0-9a-f]{32}$/;

function createResetRequestInbox(options = {}) {
  const now = typeof options.now === 'function' ? options.now : () => Date.now();
  const entries = new Map(); // nonce -> entry

  function sweep() {
    const t = now();
    for (const [nonce, e] of entries) {
      if (e.request.expiresAt <= t) { entries.delete(nonce); continue; }          // the client's own request has expired
      if (e.delivery && e.delivery.expiresAt <= t) e.delivery = null;             // the pass key itself has expired
      if (!e.delivery && t - e.lastSeenAt >= WAIT_ENTRY_TTL_MS) entries.delete(nonce);
    }
  }
  function codeInUse(code) {
    for (const e of entries.values()) if (e.pairingCode === code) return true;
    return false;
  }
  function makeRoom() {
    if (entries.size < MAX_ENTRIES) return true;
    let oldestNonce = null; let oldestSeen = Infinity;
    for (const [nonce, e] of entries) if (!e.delivery && e.lastSeenAt < oldestSeen) { oldestSeen = e.lastSeenAt; oldestNonce = nonce; }
    if (oldestNonce === null) return false;
    entries.delete(oldestNonce);
    return true;
  }
  function publicRequest(r) {
    return {
      storeName: r.storeName, deviceTag: r.deviceTag, purpose: r.purpose, includeBirData: r.includeBirData,
      createdAt: r.createdAt, expiresAt: r.expiresAt, summary: r.summary
    };
  }

  // Called by the client dialog. `installationId` MUST come from the authenticated credential, never from the request body.
  // Returns the pairing code and, once the developer has sent one, the pass key.
  function poll({ installationId, requestCode, ip }) {
    if (!installationId || typeof installationId !== 'string') return { ok: false, code: 'INVALID_INPUT' };
    const decoded = decodeRequestCode(requestCode);
    if (!decoded.ok) return { ok: false, code: 'INVALID_INPUT', message: decoded.message };
    const request = decoded.request;
    if (!NONCE_RE.test(request.nonce)) return { ok: false, code: 'INVALID_INPUT' };
    if (request.installationId !== installationId) return { ok: false, code: 'INSTALLATION_MISMATCH' };
    sweep();
    const t = now();
    if (request.expiresAt <= t) return { ok: false, code: 'REQUEST_EXPIRED' };
    const compact = String(requestCode).replace(/\s+/g, '');
    let e = entries.get(request.nonce);
    if (e) {
      // The same nonce must always describe the same action. A different action under an existing nonce is refused.
      if (e.installationId !== installationId || e.request.deviceTag !== request.deviceTag || e.request.purpose !== request.purpose || e.request.includeBirData !== request.includeBirData) {
        return { ok: false, code: 'REQUEST_MISMATCH' };
      }
      // The code is re-generated by the client each time, so its summary may be newer; the signed fields cannot change.
      e.requestCode = compact;
      e.request = request;
    } else {
      if (!makeRoom()) return { ok: false, code: 'INBOX_FULL' };
      let code = generatePairingCode();
      for (let i = 0; i < 50 && codeInUse(code); i++) code = generatePairingCode();
      if (codeInUse(code)) return { ok: false, code: 'INBOX_FULL' };
      e = { nonce: request.nonce, pairingCode: code, installationId, requestCode: compact, request, firstSeenAt: t, lastSeenAt: t, ip: ip || null, delivery: null };
      entries.set(request.nonce, e);
    }
    e.lastSeenAt = t;
    if (ip) e.ip = ip;
    if (e.delivery && !e.delivery.pickedUpAt) e.delivery.pickedUpAt = t;
    return {
      ok: true,
      pairingCode: e.pairingCode,
      requestExpiresAt: e.request.expiresAt,
      delivery: e.delivery ? { deliveryId: e.delivery.deliveryId, passKey: e.delivery.passKey, ticketId: e.delivery.ticketId, expiresAt: e.delivery.expiresAt } : null
    };
  }

  // Admin side. Returns the waiting request behind a pairing code (never the pass key), or an error code.
  function lookup(pairingCodeInput) {
    sweep();
    const code = normalizePairingCode(pairingCodeInput);
    if (!code) return { ok: false, code: 'PAIRING_CODE_INVALID' };
    for (const e of entries.values()) {
      if (e.pairingCode !== code) continue;
      if (now() - e.lastSeenAt > ONLINE_MS) return { ok: false, code: 'CLIENT_NOT_WAITING' };
      return { ok: true, entry: { pairingCode: e.pairingCode, installationId: e.installationId, requestCode: e.requestCode, nonce: e.nonce } };
    }
    return { ok: false, code: 'PAIRING_CODE_NOT_FOUND' };
  }

  // Admin side. The caller has already issued (signed) the pass key. Sending again replaces an earlier delivery.
  function send(pairingCodeInput, delivery) {
    sweep();
    const code = normalizePairingCode(pairingCodeInput);
    if (!code) return { ok: false, code: 'PAIRING_CODE_INVALID' };
    const t = now();
    for (const e of entries.values()) {
      if (e.pairingCode !== code) continue;
      const expiresAt = Number(delivery && delivery.expiresAt);
      if (!delivery || typeof delivery.passKey !== 'string' || !delivery.passKey || !Number.isFinite(expiresAt) || expiresAt <= t) return { ok: false, code: 'DELIVERY_INVALID' };
      e.delivery = {
        deliveryId: crypto.randomUUID(), passKey: delivery.passKey, ticketId: String(delivery.ticketId || ''), reference: String(delivery.reference || ''),
        sentAt: t, pickedUpAt: null, expiresAt
      };
      return { ok: true, deliveryId: e.delivery.deliveryId, installationId: e.installationId, expiresAt };
    }
    return { ok: false, code: 'PAIRING_CODE_NOT_FOUND' };
  }

  // Admin side: what the dashboard shows. Contains no pass key.
  function list() {
    sweep();
    const t = now();
    return Array.from(entries.values())
      .sort((a, b) => b.lastSeenAt - a.lastSeenAt)
      .map(e => ({
        pairingCode: e.pairingCode,
        installationId: e.installationId,
        ip: e.ip,
        firstSeenAt: e.firstSeenAt,
        lastSeenAt: e.lastSeenAt,
        online: t - e.lastSeenAt <= ONLINE_MS,
        request: publicRequest(e.request),
        delivery: e.delivery ? { sentAt: e.delivery.sentAt, pickedUpAt: e.delivery.pickedUpAt, expiresAt: e.delivery.expiresAt, ticketId: e.delivery.ticketId, reference: e.delivery.reference } : null
      }));
  }

  return { poll, lookup, send, list, _size: () => entries.size };
}

module.exports = { createResetRequestInbox, ONLINE_MS, WAIT_ENTRY_TTL_MS, MAX_ENTRIES };
